export function t(key, lang = 'en', params = {}) {
  const dict = translations[lang] || translations.en
  let str = dict[key] || translations.en[key] || key
  Object.keys(params).forEach(k => {
    str = str.replace(`{${k}}`, params[k])
  })
  return str
}

